CREATE TABLE shopping_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    description VARCHAR(50) NOT NULL,
    status VARCHAR(20) DEFAULT 'PENDING' NOT NULL CHECK ( status in ('PENDING', 'IN_PROGRESS', 'PURCHASED')),
    pending_description VARCHAR(50)
        GENERATED ALWAYS AS (
            CASE WHEN status = 'PENDING' THEN description ELSE NULL END
        ),
    CONSTRAINT uq_shopping_item_pending UNIQUE NULLS DISTINCT (pending_description)
);